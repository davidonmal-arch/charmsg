import assert from "node:assert/strict";
import { CoinbaseMarket } from "./market-data.js";
let now = Math.floor(Date.now() / 60000) * 60000 + 5000, calls = 0;
const rows = Array.from({ length: 40 }, (_, i) => [Math.floor(now / 60000) * 60 - (40 - i) * 60, 99, 101, 100, 100 + i / 100, 10]);
const ticker = { time: new Date(now).toISOString(), trade_id: 123, bid: "100", ask: "100.01", price: "100", volume: "1000" };
const market = new CoinbaseMarket({ now: () => now, sleep: async () => {}, request: async url => {
  calls++; assert.ok(url.startsWith("https://api.exchange.coinbase.com/products/BTC-USD/"));
  return { ok: true, json: async () => url.includes("candles") ? rows : ticker };
} });
assert.equal((await market.quote("BTC-USD")).closes.length, 40);
await Promise.all([market.quote("BTC-USD"), market.quote("BTC-USD")]);
assert.equal(calls, 2, "shared caches coalesce concurrent requests");
await assert.rejects(() => market.quote("https://evil.invalid"));
const down = new CoinbaseMarket({ now: () => now, sleep: async () => {}, request: async () => { throw new Error("network"); } });
assert.deepEqual((await down.quotes(["BTC-USD"])).quotes, {});
let attempts = 0;
const limited = new CoinbaseMarket({ now: () => now, sleep: async () => {}, request: async () => { attempts++; return { ok: false, status: 429 }; } });
await assert.rejects(() => limited.quote("BTC-USD")); assert.equal(attempts, 3);
const broken = new CoinbaseMarket({ now: () => now, sleep: async () => {}, request: async url => ({ ok: true, json: async () => url.includes("candles") ? rows.filter((_, i) => i !== 25) : ticker }) });
await assert.rejects(() => broken.quote("BTC-USD"), /неполная/);
console.log("Public adapter checks passed: fixed host/products, shared cache, missing history, bounded retries and unavailable provider.");
